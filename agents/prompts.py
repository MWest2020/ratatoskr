"""Context and prompt builders for the listener, kept separate so listener.py
stays under the ≤200-line convention. Pure: every dependency (root path, fleet,
name map) comes in as a parameter, no module globals from the listener.

The prompt TEXT stays Dutch: it steers a Dutch conversation with Mark. Only the
code around it is English (ADR-0001).
"""
import os
import re

_SAFE_NAME = re.compile(r"^[a-z0-9][a-z0-9_-]*$")  # channel name → file path: no ../ or /


def mentioned(content, handle):
    """Is @handle mentioned? A word boundary on both sides: on the right so
    '@architect' does not trigger on '@architectuur', on the left so
    'deploy@bouwer' (or an address in a snippet) does not count as a mention.
    Handles are a-z0-9_-."""
    return re.search(r"(?<![\w-])@" + re.escape(handle) + r"(?![\w-])", content, re.I) is not None


def channel_knowledge(root, cname):
    """Per-channel knowledge: knowledge/<channel>.md is passed as context to
    every agent turn in that channel. Empty = no extra context. The channel name
    comes from the relay (no longer from channels.yml alone), so we validate it
    strictly against `_SAFE_NAME` before it ends up in a path — otherwise a
    `../..` name would give a path-traversal read."""
    if not _SAFE_NAME.match(cname or ""):
        return ""
    try:
        return open(os.path.join(root, "knowledge", f"{cname}.md")).read().strip()[:4000]
    except OSError:
        return ""


def live_text(root):
    """What is running now (knowledge/_live.md, generated by
    orchestrator/live.py) — liveness context for the hub. Empty = unknown."""
    try:
        return open(os.path.join(root, "knowledge", "_live.md")).read().strip()[:4000]
    except OSError:
        return ""


def roster_text(agents, hub=None):
    """Short summary of the current fleet — context for the hub. `hub` is left
    out of the list: it learns nothing new about itself."""
    lines = ["Huidige agent-vloot (uit de handbook-registry):"]
    for h, c in agents.items():
        if h == hub:
            continue
        first = (c.get("system", "").strip().split("\n", 1)[0])[:110]
        lines.append(f"- @{h} (kanalen: {','.join(c['channels'])}) — {first}")
    return "\n".join(lines)


def session_clause(cfg, handle, requester=None):
    """What this agent can start itself, told in its system prompt.

    Without this line an agent does not know work sessions exist: on 2026-09-09
    odin reported in #general (rightly) "ik heb geen tool-toegang tot een
    tmux-sessie op agent@agent-lxc". This tells it what it DOES have. It widens
    no mandate — who may start which type lives in sessions.yml and is enforced
    there; this is only the announcement. `requester` = the person the agent
    would start on behalf of; types that person may not use are not named."""
    starters = (cfg or {}).get("types") or {}
    types = {n: t for n, t in starters.items()
             if handle in (t.get("starters") or [])
             # The requester must be allowed to start the type too — otherwise
             # the agent announces a session that gets an immediate ⛔.
             and (requester is None or requester in (t.get("starters") or []))}
    if not types:
        return ""
    lines = "\n".join(f"- `{n}` — {t.get('description') or t.get('workdir', '')}"
                     for n, t in sorted(types.items()))
    return ("\n\nJe kunt zelf een WERKSESSIE starten: een langere, LEZENDE claude-run "
            "met eigen gereedschap en eigen werkmap, die zijn resultaat in dit kanaal "
            "post. Zet daarvoor als LAATSTE regel van je antwoord precies:\n"
            "!sessie <type> <opdracht in een zin>\n"
            f"Beschikbare types:\n{lines}\n"
            "Doe dat alleen als het gevraagde werk echt uitzoeken vergt — voor een "
            "gesprek antwoord je zelf. Hoogstens één sessie per antwoord, en zeg in "
            "je eigen woorden dat je 'm start. Een sessie leest en stelt voor; hij "
            "verandert niets.")


def build_prompt(handle, chan, recent, trigger, pub2name):
    lines = [f"Kanaal #{chan}. Recente berichten:"]
    for m in recent:
        who = pub2name.get(m.get("pubkey", ""), "iemand")
        lines.append(f"{who}: {m.get('content','')}")
    lines.append("")
    lines.append(f"Je bent '{handle}'. Reageer als vervolg op het gesprek "
                 f"hierboven, op dit laatste bericht: {trigger!r}")
    return "\n".join(lines)


